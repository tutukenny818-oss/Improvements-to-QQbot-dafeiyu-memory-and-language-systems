# -*- coding: utf-8 -*-
"""已被推翻的说法：检索时给命中打「已过时」标记。

## 为什么需要这个文件

有些记忆段落**记录了当时说的话，但那个说法后来被推翻了**。
删掉它们是不对的 —— 那是真实发生过的对话，而且"它曾经这么说过"
本身是有价值的历史。

但**不标注就会误导**。实测（第 189 轮）：

    问「大肥鱼的形象设定是什么」，检索返回 10 条：
      [0.655] 大肥鱼确认自己的形象就是本设定中的样子：蓝紫渐变长发…   ← 正确
      [0.572] 大肥鱼确认全网现在认准她的形象是蓝发黑西装…            ← 旧说法
      [0.552] …大肥鱼从B站分享…并确认全网现在认准她的形象是蓝发黑西装  ← 旧说法
      [0.502] …并确认全网现在认准她的形象是蓝发黑西装…               ← 旧说法

    模型看到 3 条矛盾内容 + 1 条正确内容 → 判"无法确定哪个是最新"
    → 严评失败（14/15）

正确内容明明是**第 1 名**。问题不是排序错，是**没告诉模型"后面那些是旧的"**。

## 设计

每条规则 = 一个话题 + 一组关键词 + 一句说明。

命中段落包含 `match` 里的任一关键词 → 在 metadata 打 `stale_topic`，
渲染时显示「⚠旧说法」前缀，模型就知道该以哪个为准。

## 依据

[MS-TOD (arXiv:2505.20231)](https://arxiv.org/abs/2505.20231) 的
`confirmation state` 思路：状态变化要**显式记录**，不能靠读者自己推断。
[Zep (arXiv:2501.13956)](https://arxiv.org/abs/2501.13956) 也说
失效的边要标 `t_invalid`，但**保留在历史里**（preserved as history）。

## 怎么加新规则

如果以后发现某类说法被推翻（比如"大肥鱼的称号是X"改口了），
在这里加一条即可，不用改代码：

    {
        "topic": "称号",
        "match": ("称号是果壳常客", "称号：果壳常客"),
        "note": "大肥鱼的称号以「果壳元老」为准（2026-10-21 更新）",
    }

## 注意

`match` 要写得**够具体** —— 太泛会把正确内容也标掉。
例如不能只写 `"西装"`，因为正确段落里也可能提到"不是黑西装"。
"""
from __future__ import annotations

from typing import Any, Dict, List, Tuple

# 每条：(话题, 旧说法的特征词, 说明)
STALE_RULES: List[Dict[str, Any]] = [
    {
        "topic": "形象设定",
        # 只匹配"确认/认准…蓝发黑西装"这类**肯定性**表述。
        # 不匹配单纯出现"黑西装"三个字的段落
        # （"女仆装那个不是我"这种否认句里也可能有）。
        "match": (
            "认准她的形象是蓝发黑西装",
            "认准她的 DeepSeek 形象是蓝发黑西装",
            "形象是蓝发黑西装，并接受",
            "认准她形象是蓝发黑西装",
        ),
        "note": (
            "大肥鱼的形象以人设为准：蓝紫到浅蓝渐变长发、深蓝配白小裙子、"
            "白褶边围裙绣小鲸鱼、蓝色鱼尾、鳍状发饰。"
            "「蓝发黑西装」是 B 站评论区传的说法，她当时跟着认了，"
            "但这与设定不符，**不是她的样子**。"
        ),
    },
]


def find_stale_topic(text: str) -> Tuple[str, str]:
    """判断一段正文是否属于「已被推翻的说法」。

    返回 `(topic, note)`；不是旧说法则返回 `("", "")`。

    只看正文，不看 metadata —— 因为这些段落入库时还没有这套机制，
    靠打标是补不上的，只能每次检索时现算（成本是一次字符串包含检查）。
    """
    body = str(text or "")
    if not body:
        return "", ""
    for rule in STALE_RULES:
        for kw in rule.get("match") or ():
            if kw and kw in body:
                return str(rule.get("topic") or ""), str(rule.get("note") or "")
    return "", ""
